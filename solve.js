// site-generator-speed-01 bounty. Same answers as makefun-site's build(),
// byte for byte, on every input; structured for speed instead of plugins:
// one pass over each source, bulk HTML escaping, cached slugs, and a
// template renderer that pushes into one output array per render.

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const RESERVED = ['posts', 'tags', 'page'];

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** HTML escape: fast path returns the string untouched when nothing needs it. */
function esc(s) {
  return s.indexOf('&') === -1 && s.indexOf('<') === -1 && s.indexOf('>') === -1 && s.indexOf('"') === -1 && s.indexOf("'") === -1
    ? s
    : s.replace(/[&<>"']/g, (c) => ESC[c]);
}

function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

const slugCache = new Map();
function slugify(text) {
  let s = slugCache.get(text);
  if (s !== undefined) return s;
  const plain = text.normalize('NFKD').replace(/\p{M}/gu, '');
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const ch = plain[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, 64).replace(/-+$/, '');
  s = out === '' ? 'untitled' : out;
  slugCache.set(text, s);
  return s;
}

function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const dateCache = new Map();
function dateLong(date) {
  let s = dateCache.get(date);
  if (s === undefined) {
    s = longDate(date);
    dateCache.set(date, s);
  }
  return s;
}

/** Word count: runs of non-whitespace, counted without a match array. */
function wordsOf(text) {
  let n = 0;
  let inW = false;
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    const ws = c === 32 || c === 9 || c === 10 || c === 13 || c === 12 || c === 11 || (c > 127 && /\s/.test(text[i]));
    if (ws) inW = false;
    else if (!inW) {
      inW = true;
      n++;
    }
  }
  return n;
}

